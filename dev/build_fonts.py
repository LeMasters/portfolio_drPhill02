#!/usr/bin/env python3
"""
Regenerate themes/DrPhill/static/fonts/ and themes/DrPhill/assets/css/fonts.css
from the Fontsource font files (github.com/fontsource/font-files).

1. Fetch only the needed folders (run from any scratch directory):
     git clone --depth 1 --filter=blob:none --sparse https://github.com/fontsource/font-files ff
     cd ff && git sparse-checkout set --no-cone \
       'fonts/variable/<package>/files/*latin-*' 'fonts/variable/<package>/*.css' 'fonts/variable/<package>/LICENSE'
     (repeat the three patterns for each package in FAMILIES below)
2. Run:  python3 -I dev/build_fonts.py <path to ff/fonts/variable> <path to themes/DrPhill>

To add or swap a typeface: edit FAMILIES (Fontsource package name → short key used in
data/style.yaml), rerun, then add the key to section 1/2 of main.css, the $fonts map in
baseof.html, and the two select fields in .pages.yml.
"""
import os, re, shutil, sys

FAMILIES = {
    "atkinson-hyperlegible-next": "atkinson",
    "inter": "inter",
    "source-serif-4": "source-serif",
    "fraunces": "fraunces",
}
SUBSET = re.compile(r"-latin(-ext)?-wght-(normal|italic)$")   # Latin + Latin Extended, weight axis

src, theme = sys.argv[1], sys.argv[2]
out = ["/* Four open-licence (SIL OFL 1.1) variable fonts, served from this site.",
       "   Latin and Latin Extended subsets, weight axis only, normal and italic.",
       "   Browsers download a file only when a page actually uses that face and those characters.",
       "   Generated by dev/build_fonts.py from the Fontsource packages (fontsource/font-files). */", ""]
for pkg, key in FAMILIES.items():
    dest = os.path.join(theme, "static", "fonts", key)
    shutil.rmtree(dest, ignore_errors=True); os.makedirs(dest)
    shutil.copy(os.path.join(src, pkg, "LICENSE"), os.path.join(dest, "OFL.txt"))
    for css in ["wght.css", "wght-italic.css"]:
        text = open(os.path.join(src, pkg, css)).read()
        for m in re.finditer(r"/\* ([^*]+) \*/\s*(@font-face \{.*?\})", text, re.S):
            name, block = m.group(1).strip(), m.group(2)
            if not SUBSET.search(name):
                continue
            fn = re.search(r"\./files/([^)]+\.woff2)", block).group(1)
            shutil.copy(os.path.join(src, pkg, "files", fn), os.path.join(dest, fn))
            out.append(f"/* {name} */\n" + block.replace(f"./files/{fn}", f"../fonts/{key}/{fn}") + "\n")
open(os.path.join(theme, "assets", "css", "fonts.css"), "w").write("\n".join(out))
print("Wrote", len(out) - 5, "@font-face rules")
